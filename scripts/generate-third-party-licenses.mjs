#!/usr/bin/env node
/**
 * generate-third-party-licenses.mjs - T1.9 dependency license inventory.
 *
 * Walks the installed npm tree (node_modules) and the vendored Cargo registry
 * sources (~/.cargo/registry/src) to produce THIRD_PARTY_LICENSES.md.
 * Run wherever dependencies are installed:  node scripts/generate-third-party-licenses.mjs
 * (CI can run it as a report job; the committed file is refreshed with releases.)
 */
import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";
import os from "node:os";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const licenses = new Map(); // "name@version" -> license

function add(name, version, license, kind) {
  const key = `${name}@${version}`;
  const existing = licenses.get(key);
  if (existing && existing.license === license) return;
  licenses.set(key, { name, version, license: license || "UNKNOWN", kind });
}

// --- npm tree ---
const nm = join(root, "node_modules");
function scanNpm(dir, depth) {
  if (depth > 6) return;
  for (const entry of readdirSync(dir)) {
    if (entry.startsWith(".")) continue;
    const p = join(dir, entry);
    if (!statSync(p).isDirectory()) continue;
    const scoped = entry.startsWith("@");
    if (scoped) { scanNpm(p, depth + 1); continue; }
    const pkgJson = join(p, "package.json");
    if (existsSync(pkgJson)) {
      try {
        const pkg = JSON.parse(readFileSync(pkgJson, "utf8"));
        // A package.json without a name is a subpath folder inside a real
        // package (e.g. nanoid/async), not a dependency — skip it so the
        // inventory does not carry a phantom "async | ? | UNKNOWN" row.
        if (!pkg.name) { /* subpath folder, covered by its parent */ }
        else add(pkg.name, pkg.version || "?", pkg.license, "npm");
      } catch { /* skip malformed */ }
    }
    scanNpm(p, depth + 1);
  }
}
if (existsSync(nm)) scanNpm(nm, 0);

// --- cargo registry sources ---
const cargoSrc = join(os.homedir(), ".cargo", "registry", "src");
if (existsSync(cargoSrc)) {
  for (const idx of readdirSync(cargoSrc)) {
    const idxDir = join(cargoSrc, idx);
    for (const crateDir of readdirSync(idxDir)) {
      // crate dirs look like "name-1.2.3" (may end with .github-suffixes rarely)
      const tomlPath = join(idxDir, crateDir, "Cargo.toml");
      if (!existsSync(tomlPath)) continue;
      const m = crateDir.match(/^(.*)-([0-9]+\.[0-9]+\.[0-9]+.*)$/);
      const name = m ? m[1] : crateDir;
      const version = m ? m[2] : "?";
      try {
        const toml = readFileSync(tomlPath, "utf8");
        const pkgSec = toml.match(/\[package\][\s\S]*?(?=\n\[|$)/)?.[0] || "";
        const lic = pkgSec.match(/^license\s*=\s*"([^"]+)"/m)?.[1]
          || pkgSec.match(/^license-file\s*=\s*"([^"]+)"/m)?.[1];
        add(name, version, lic, "cargo");
      } catch { /* skip */ }
    }
  }
}

const PROBLEM = /(GPL|AGPL|LGPL|SSPL|EUPL|Commons Clause|OSL|QPL|CPL|EPL)/i;
const rows = [...licenses.values()].sort((a, b) =>
  a.kind.localeCompare(b.kind) || a.name.toLowerCase().localeCompare(b.name.toLowerCase()));

let md = `# Third-party licenses\n\nGenerated by \`scripts/generate-third-party-licenses.mjs\` on ${new Date().toISOString().slice(0, 10)} from the installed npm tree and the local Cargo registry cache. ScholarScribe is MIT licensed; it links the dependencies below.\n\n`;
for (const kind of ["npm", "cargo"]) {
  const subset = rows.filter((r) => r.kind === kind);
  md += `## ${kind === "npm" ? "npm dependencies (frontend toolchain and runtime)" : "Rust crates (src-tauri backend)"} (${subset.length})\n\n| Package | Version | License |\n|---|---|---|\n`;
  for (const r of subset) md += `| ${r.name} | ${r.version} | ${r.license} |\n`;
  md += "\n";
}
const problems = rows.filter((r) => PROBLEM.test(r.license));
if (problems.length) {
  md += `## License review flags\n\nThe following declare licenses with copyleft or attribution-service terms. They are build-time tooling or vendored programs, not linked runtime code, unless noted:\n\n`;
  for (const p of problems) md += `- **${p.name}@${p.version}** (${p.kind}): ${p.license}\n`;
  md += `\nMaintainer review required before any of these become runtime-linked dependencies (work order N4). Pandoc (GPL-2.0-or-later) is deliberately NOT bundled and must remain a separate, user-installed program.\n`;
} else {
  md += `## License review flags\n\nNone. No copyleft or attribution-service licenses found in the installed dependency tree.\n`;
}
writeFileSync(join(root, "THIRD_PARTY_LICENSES.md"), md);
console.log(`THIRD_PARTY_LICENSES.md written: ${rows.length} packages (${problems.length} flagged)`);
